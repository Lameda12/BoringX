import { describe, expect, it, afterAll } from "vitest";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawn, type ChildProcess } from "node:child_process";

const read = (p: string) => fs.readFileSync(p, "utf8");
const repo = process.cwd();

describe("Docker self-hosting", () => {
  it("ships a Dockerfile that builds with npm ci + npm run build and serves with the header-aware server", () => {
    expect(fs.existsSync("Dockerfile")).toBe(true);
    const d = read("Dockerfile");
    expect(d).toMatch(/npm ci/);
    expect(d).toMatch(/npm run build/);
    expect(d).toMatch(/scripts\/serve\.mjs/);
    expect(d).toMatch(/vercel\.json/);
    expect(d).toMatch(/COPY --from=build [^\n]*out/);
    expect(d).toMatch(/^USER\s+(?!root)/m);
    expect(d).toMatch(/HEALTHCHECK/);
    expect(d).toMatch(/ARG SITE_URL/);
    expect(d).toMatch(/COPY scripts\/serve\.mjs/);
    expect(fs.existsSync("scripts/serve.mjs") && fs.existsSync("vercel.json")).toBe(true);
  });
  it(".dockerignore keeps host build output and dependencies out of the context", () => {
    expect(fs.existsSync(".dockerignore")).toBe(true);
    const lines = read(".dockerignore").split("\n").map((l) => l.trim());
    for (const entry of ["node_modules", ".next", "out", ".git"]) expect(lines).toContain(entry);
    expect(lines).not.toContain("vercel.json");
    expect(lines).not.toContain("public");
    // generated assets are excluded from the context but must be regenerated by the build
    expect(read("scripts/copy-assets.mjs")).toMatch(/imgly[\s\S]*tesseract|tesseract[\s\S]*imgly/);
    for (const entry of ["public/imgly", "public/tesseract", "public/codecs"]) expect(lines).toContain(entry);
    expect(JSON.parse(read("package.json")).scripts.prebuild).toContain("copy-assets.mjs");
  });
  it("README documents the Docker commands, first-use downloads and the offline limits", () => {
    const r = read("README.md");
    expect(r).toMatch(/docker build/);
    expect(r).toMatch(/docker run/);
    expect(r).toMatch(/Content-Security-Policy/);
    expect(r).toMatch(/\/remove-background/);
    expect(r).toMatch(/generic static|nginx|plain static/i);
    expect(r).toMatch(/offline/i);
    expect(r).toMatch(/SITE_URL/);
    expect(r).toMatch(/AVIF/);
    expect(r).toMatch(/HTTPS/);
  });
});

describe("serve.mjs applies route-specific headers (what the container runs)", () => {
  let child: ChildProcess | undefined;
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "bx-serve-"));
  const port = 4900 + Math.floor(Math.random() * 1000);
  afterAll(() => { child?.kill(); fs.rmSync(dir, { recursive: true, force: true }); });

  it("serves default, worker and remove-background CSPs as in vercel.json", async () => {
    fs.mkdirSync(path.join(dir, "out/workers"), { recursive: true });
    fs.writeFileSync(path.join(dir, "out/index.html"), "ok");
    fs.writeFileSync(path.join(dir, "out/remove-background.html"), "rb");
    fs.writeFileSync(path.join(dir, "out/workers/custom.html"), "w");
    fs.copyFileSync(path.join(repo, "vercel.json"), path.join(dir, "vercel.json"));
    child = spawn("node", [path.join(repo, "scripts/serve.mjs")], { cwd: dir, env: { ...process.env, PORT: String(port) } });
    await new Promise((r, j) => { child!.stdout!.once("data", r); child!.once("exit", () => j(new Error("server exited"))); setTimeout(() => j(new Error("server start timeout")), 5000); });
    const get = async (p: string) => (await fetch(`http://127.0.0.1:${port}${p}`)).headers.get("content-security-policy") ?? "";
    expect(await get("/")).toContain("connect-src 'self' blob: data:");
    expect(await get("/")).not.toContain("'unsafe-eval'");
    expect(await get("/remove-background")).toContain("'unsafe-eval'");
    expect(await get("/workers/custom")).toContain("connect-src 'none'");
    expect(await get("/workers/custom")).toContain("default-src 'none'");
    // malformed percent-encoding must not crash the server
    expect((await fetch(`http://127.0.0.1:${port}/%`)).status).toBe(400);
    expect(await get("/")).toContain("worker-src 'self' blob:");
  });
});
